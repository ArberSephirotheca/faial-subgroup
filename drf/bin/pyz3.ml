let proof_to_smt2 ~(logic : string option) (goal : Exp.bexp) : string =
  let encode (enc : Encoder.t) : string =
    let ctx = Z3.mk_context [] in
    let s = Z3.Solver.mk_simple_solver ctx in
    Z3.Solver.add s [ enc.b_to_expr ctx (Predicates.b_inline goal) ];
    Z3.Solver.to_string s
  in
  try encode (Encoder.initial ~logic)
  with Gen_z3.Not_implemented _ -> encode (Encoder.bv64 ())

let py_str (s : string) : string =
  let buf = Buffer.create (String.length s + 2) in
  Buffer.add_char buf '"';
  String.iter
    (function
      | '"' -> Buffer.add_string buf "\\\""
      | '\\' -> Buffer.add_string buf "\\\\"
      | c -> Buffer.add_char buf c)
    s;
  Buffer.add_char buf '"';
  Buffer.contents buf

let py_val (s : string) : string =
  match int_of_string_opt s with Some n -> string_of_int n | None -> py_str s

let py_dict (kvs : (string * string) list) : string =
  "{"
  ^ (kvs
    |> List.map (fun (k, v) -> py_str k ^ ": " ^ py_val v)
    |> String.concat ", ")
  ^ "}"

let py_list (elems : string list) : string =
  "[" ^ String.concat ", " elems ^ "]"

let rec py_of_json (j : Yojson.Basic.t) : string =
  match j with
  | `String s -> py_str s
  | `Int n -> string_of_int n
  | `Bool b -> if b then "True" else "False"
  | `Float f -> string_of_float f
  | `Null -> "None"
  | `List xs -> "[" ^ (xs |> List.map py_of_json |> String.concat ", ") ^ "]"
  | `Assoc kvs ->
      "{"
      ^ (kvs
        |> List.map (fun (k, v) -> py_str k ^ ": " ^ py_of_json v)
        |> String.concat ", ")
      ^ "}"

