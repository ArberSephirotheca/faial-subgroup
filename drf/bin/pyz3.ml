# One-line gloss per `$T<k>$...` internal access descriptor (see
# `describe_symbol`). `<k>` is the racing task, 1 or 2.
_ACCESS_DESC = {
    "id": "which flattened access the thread took",
    "mode": "access mode (0 read, 1 write, 2 atomic at device scope, "
    "3 atomic at block scope)",
    "wknown": "1 if the written value is statically known, else 0",
    "wval": "the written value",
}

# One-line gloss per `@`-prefixed synthesized-variable family. The `@` prefix
# (no C or WGSL identifier can contain it) marks a value faial made up because
# it could not keep the source expression; the rest of the name records the
# origin. `describe_symbol` matches longest-prefix-first, defensively, so a
# future family whose name extends another's still resolves correctly.
_AT_FAMILY = {
    "@Unknown": "an expression faial could not translate (a black box); "
    "its `label` names the source construct",
    "@AccessState": "a read / atomic / call / hoisted-expression / write "
    "value result (the CUDA path names all of these alike)",
    "@Launch": "a <<<grid, block>>> launch argument, or a host value "
    "computed for one",
    "@vec_return": "an inlined vector-constructor return; its .x/.y/.z/.w "
    "lanes are assigned separately",
    "@Call": "a WGSL function-call result",
    "@Atomic": "a WGSL atomic-operation result",
    "@WorkGroupUniformLoad": "a WGSL workgroup-uniform-load result",
    "@SubgroupBallot": "a WGSL subgroup-ballot result",
    "@SubgroupOperation": "a WGSL subgroup-operation result",
    "@thread_unif": "an uninterpreted function standing for a "
    "thread-uniform value",
    "@atomic_result": "an uninterpreted function standing for an atomic "
    "operation's result",
}


def describe_symbol(name: str) -> str:
    """One-line gloss for any solver symbol or witness name, decoding faial's
    sigils. Four families appear in a Proof:

    * a plain source name (`n`, `threadIdx.x`) is a program variable;
      `variables[name].kind` says which role it plays;
    * a `$T1` / `$T2` *suffix* is a thread-local projected onto the racing
      pair: `i$T1` is thread 1's `i`, `i$T2` thread 2's;
    * an `@`-*prefix* marks a value faial synthesized because it could not
      keep the source expression; these appear in `Proof.variables`, and the
      `@`-name is the only record of the value's origin;
    * a `$`-*prefix* marks faial's internal per-access SMT descriptor; these
      appear only in the raw solver assertions, never in `Proof.variables`.
    """
    m = re.fullmatch(r"\$T(\d+)\$(.+)", name)
    if m:
        task, rest = m.group(1), m.group(2)
        idx = re.fullmatch(r"idx\$(\d+)", rest)
        if idx:
            return f"task {task}: access address in dimension {idx.group(1)}"
        return f"task {task}: " + _ACCESS_DESC.get(
            rest, f"internal descriptor {rest!r}"
        )
    m = re.search(r"\$T([12])$", name)
    if m:
        base = name[: m.start()]
        return f"thread {m.group(1)}'s value of {base!r} ({describe_symbol(base)})"
    for prefix in sorted(_AT_FAMILY, key=len, reverse=True):
        if name.startswith(prefix):
            return _AT_FAMILY[prefix]
    if name.startswith("@"):
        return "a synthesized symbol faial introduced (the @ prefix marks a non-source name)"
    return "a source-level program variable"


@dataclass
class Task:
    """One conflicting thread: its local variable values (threadIdx.{x,y,z}
    and loop counters), the access mode ('ro' read / 'rw' write), the source
    location of the racing access, and `access_id`, the stable per-kernel id
    of the static access this thread took. `access_id` is the value the raw
    SMT binds to this task's `$T<k>$id` symbol, so it cross-references a model
    back to a specific source access."""

    locals: dict
    mode: str
    location: dict
    access_id: int


class VariableKind(enum.Enum):
    """Mirrors faial's Variable.Kind, one member per OCaml variant."""

    SYNTHESIZED = "synthesized"
    LAUNCH_PARAMETER = "launch-parameter"
    READ_RESULT = "read-result"
    FUNCTION_RESULT = "function-result"
    ATOMIC_RESULT = "atomic-result"
    KERNEL_PARAMETER = "kernel-parameter"
    DECL = "decl"
    LOOP_VARIABLE = "loop-variable"
    ARRAY = "array"
    GPU_RUNTIME = "gpu-runtime"


@dataclass
class Variable:
    """Everything faial knows about one z3 symbol in a Proof, keyed in
    `Proof.variables` by the solver symbol as it appears in the SMT.

    A thread-local reads as `X$T1` (task1) / `X$T2` (task2); a
    thread-uniform value (kernel parameter, blockDim, gridDim, and, in a
    block-level proof, blockIdx) keeps its plain name. `kind` is the source
    classification. `task` is 1, 2, or None, and `thread_uniform` is True
    exactly when `task is None` (both threads share the value in this
    block/grid mode). `control_precise` / `data_precise` are False when the
    symbol is over-approximated in the reaching condition / the address; a
    non-precise data symbol is a data-dependent index no parameter
    assumption can discharge. `filename`/`line`/`col_start`/`col_finish`
    are the base-1 source location, all None when faial has none.

    Only source-level variables appear; faial's synthesized symbols (a
    leading `$`) are excluded, so `variables["$x"]` raises KeyError. A key may
    still be an `@`-synthesized value; call `describe_symbol(key)` for a
    one-line gloss of any symbol, including the `$`-prefixed internals that
    surface only in the raw solver."""

    kind: VariableKind
    task: int | None
    thread_uniform: bool
    control_precise: bool
    data_precise: bool
    filename: str | None = None
    line: int | None = None
    col_start: int | None = None
    col_finish: int | None = None


@dataclass
class Proof:
    """A racy proof obligation from faial-drf, ready to explore in z3.

    `solver.check()` returns sat and reproduces the counterexample faial
    found. `array` and `indices` are the array and the subscript where the
    two threads collide. `globals` is the shared parameter/geometry
    assignment it chose; `task1` and `task2` are the two colliding threads
    (each a Task with `locals`, `mode`, and the access `location`).
    `variables` maps every source-level solver symbol to a `Variable` with
    its kind, task, thread-uniformity, precision, and source location (see
    `Variable`); an all-precise proof is a precise counterexample (CIDI).
    `logic` is the user-requested z3 logic, if any, and is informational;
    `is_bv` is the authoritative sort flag: the whole proof is encoded in
    64-bit bit-vectors when True, otherwise in Int. A thread-local `X` is the
    solver constant `X$T1` for task1 and `X$T2` for task2; globals keep their
    plain name, and sym()/var() translate between the dict keys and the solver
    symbols. Build a constant of the right sort with `const`, then probe a
    candidate assumption with `check` (an isolated child solver, so the base
    query is left intact):

        p = proofs[0]
        p.solver.check()                        # sat: the race faial found
        p.globals                               # {'nb1': 0, ...}
        p.check(p.const("blockDim.x") == 1)     # unsat: that removes this witness
        p.refutes(p.const("nb1") >= p.const("ne00"))  # True if that clears it

    An unsat (refutes True) means the constraint removes this counterexample:
    a lead, not a DRF proof (one proof, no reachability or vacuity gate).
    Confirm a promising assumption with `faial-drf --assume "..."`.
    """

    kernel: str
    array: str
    indices: list
    globals: dict
    task1: Task
    task2: Task
    variables: dict
    logic: str | None
    is_bv: bool
    solver: z3.Solver

    @classmethod
    def from_smt2(
        cls,
        kernel: str,
        array: str,
        indices: list,
        globals: dict,
        task1: Task,
        task2: Task,
        variables: dict,
        logic: str | None,
        is_bv: bool,
        smt2: str,
    ) -> "Proof":
        solver = z3.Solver()
        solver.add(z3.parse_smt2_string(smt2))
        return cls(
            kernel, array, indices, globals, task1, task2,
            variables, logic, is_bv, solver,
        )

    def sym(self, name: str, task: int | None = None) -> str:
        """z3 symbol name for a high-level variable: the plain name for a
        global, or `name$T1` / `name$T2` for a task1 / task2 local."""
        return name if task is None else f"{name}$T{task}"

    def var(self, symbol: str) -> tuple[int | None, str] | None:
        """Inverse of sym: (task, name) for a solver symbol, task being 1, 2,
        or None (a global); None for faial's internal $-prefixed symbols.
        Cross-reference a model with: `p.var(d.name())` for `d` in model."""
        for t in (1, 2):
            suffix = f"$T{t}"
            if symbol.endswith(suffix):
                return t, symbol[: -len(suffix)]
        return None if symbol.startswith("$") else (None, symbol)

    def const(self, name: str, task: int | None = None) -> z3.ExprRef:
        """A z3 constant for a witness variable, of this proof's sort. Pass the
        faial name (the witness-dict key: `nb1`, `i00`, `@Unknown0`); the
        `$T1` / `$T2` suffix is added for a task-local. Returns `BitVec(_, 64)`
        when `is_bv`, else `Int`, matching the sort the emitted SMT declares."""
        s = self.sym(name, task)
        return z3.BitVec(s, 64) if self.is_bv else z3.Int(s)

    def check(self, *constraints, timeout_ms: int = 10_000):
        """Does the race survive if `constraints` also hold? Runs on a fresh
        child solver seeded with the base assertions plus `constraints`, so the
        base query stays intact and unbounded. Returns z3 `sat` (still racy),
        `unsat` (this witness refuted), or `unknown` (hit `timeout_ms`: raise
        it, or substitute the witness's concrete values). Mirrors
        `z3.Solver.check(*assumptions)`; adds no standing assumption."""
        child = z3.Solver()
        child.set("timeout", timeout_ms)
        child.add(self.solver.assertions())
        child.add(*constraints)
        return child.check()

    def refutes(self, *constraints, timeout_ms: int = 10_000) -> bool:
        """`check(...) == unsat`: True when `constraints` refute this witness."""
        return self.check(*constraints, timeout_ms=timeout_ms) == z3.unsat

    def is_index_precise(self) -> bool:
        """The colliding index is exact: no over-approximated data symbol."""
        return all(v.data_precise for v in self.variables.values())

    def is_control_flow_precise(self) -> bool:
        """The reaching condition is exact: no over-approximated control symbol."""
        return all(v.control_precise for v in self.variables.values())

    def is_precise(self) -> bool:
        """Both index and control flow are exact: a precise counterexample."""
        return self.is_index_precise() and self.is_control_flow_precise()

    def affects_index_precision(self) -> list:
        """Solver symbols left free in the address (data_precise is False)."""
        return [s for s, v in self.variables.items() if not v.data_precise]

    def affects_control_flow_precision(self) -> list:
        """Solver symbols left free in the reaching condition (control_precise is False)."""
        return [s for s, v in self.variables.items() if not v.control_precise]

    def approx_analysis(self) -> str:
        """The four-letter display code: CD/CI (control) then DD/DI (data)."""
        cd = "CI" if self.is_control_flow_precise() else "CD"
        dd = "DI" if self.is_index_precise() else "DD"
        return cd + dd


