type pyz3_proof = {
  kernel : string;
  array : string;
  indices : string;
  globals : string;
  task1 : string;
  task2 : string;
  variables : string;
  logic : string;
  is_bv : string;
  smt : string;
}

(* Split a solver symbol into its task (from the [$T1]/[$T2] projection
   suffix) and the high-level base name. A thread-uniform symbol has no
   suffix and task [None]. *)
let split_task (name : string) : int option * string =
  let strip (t : int) : string option =
    let suffix = "$T" ^ string_of_int t in
    if String.ends_with ~suffix name then
      Some (String.sub name 0 (String.length name - String.length suffix))
    else None
  in
  match strip 1 with
  | Some base -> (Some 1, base)
  | None -> (
      match strip 2 with Some base -> (Some 2, base) | None -> (None, name))

let py_kind (k : Variable.Kind.t) : string =
  let open Variable.Kind in
  "VariableKind."
  ^
  match k with
  | Synthesized -> "SYNTHESIZED"
  | LaunchParameter -> "LAUNCH_PARAMETER"
  | ReadResult -> "READ_RESULT"
  | FunctionResult -> "FUNCTION_RESULT"
  | AtomicResult -> "ATOMIC_RESULT"
  | KernelParameter -> "KERNEL_PARAMETER"
  | Decl -> "DECL"
  | LoopVariable -> "LOOP_VARIABLE"
  | Array -> "ARRAY"
  | GpuRuntime -> "GPU_RUNTIME"

let py_variable ~(task : int option) ~(kind : Variable.Kind.t)
    ~(control_precise : bool) ~(data_precise : bool)
    ~(location : Stage0.Location.t option) : string =
  let py_bool b = if b then "True" else "False" in
  let loc_args =
    match location with
    | None -> ""
    | Some loc ->
        let iv = Stage0.Location.interval loc in
        Printf.sprintf ", filename=%s, line=%d, col_start=%d, col_finish=%d"
          (py_str (Stage0.Location.filename loc))
          (Stage0.Location.line loc |> Stage0.Index.to_base1)
          (Stage0.Interval.start iv |> Stage0.Index.to_base1)
          (Stage0.Interval.finish iv |> Stage0.Index.to_base1)
  in
  Printf.sprintf
    "Variable(kind=%s, task=%s, thread_uniform=%s, control_precise=%s, \
     data_precise=%s%s)"
    (py_kind kind)
    (match task with Some t -> string_of_int t | None -> "None")
    (py_bool (task = None))
    (py_bool control_precise) (py_bool data_precise) loc_args

let to_pyz3_proof (kernel_name : string) (s : Solution.t) : pyz3_proof option =
  let open Solution in
  match s.outcome with
  | Outcome.Racy w ->
      let p : Symbexp.Proof.t = s.proof in
      let task (t : TaskState.t) : string =
        Printf.sprintf "Task(%s, %s, %s, %d)"
          (py_dict (Environ.variables t.locals))
          (py_str (Access.Mode.to_string (Access.mode t.access)))
          (py_of_json (Stage0.Location.to_json (Access.location t.access)))
          (Access.id t.access |> Access.Id.to_int)
      in
      let t1, t2 = w.tasks in
      let variables =
        let names (vars : Variable.Set.t) : string list =
          Variable.Set.elements vars |> List.map Variable.name
        in
        let data_names = names w.data_approx in
        let ctrl_names = names w.control_approx in
        Exp.b_free_names p.goal Variable.Set.empty
        |> Variable.Set.elements
        (* Drop faial's synthesized symbols; only source variables belong. *)
        |> List.filter (fun v ->
               not (String.starts_with ~prefix:"$" (Variable.name v)))
        |> List.map (fun v ->
               let symbol = Variable.name v in
               let task, base = split_task symbol in
               py_str symbol ^ ": "
               ^ py_variable ~task ~kind:(Variable.kind v)
                   ~control_precise:(not (List.mem base ctrl_names))
                   ~data_precise:(not (List.mem base data_names))
                   ~location:(Variable.location_opt v))
        |> String.concat ", "
      in
      let smt = proof_to_smt2 ~is_bv:s.is_bv p.goal in
      Some
        {
          kernel = py_str kernel_name;
          array = py_str p.array_name;
          indices = py_list (List.map py_val w.indices);
          globals = py_dict (Environ.variables w.globals);
          task1 = task t1;
          task2 = task t2;
          variables = "{" ^ variables ^ "}";
          logic = (match s.logic with Some l -> py_str l | None -> "None");
          is_bv = (if s.is_bv then "True" else "False");
          smt;
        }
  | _ -> None

let serialize (oc : out_channel) (p : pyz3_proof) : unit =
  Printf.fprintf oc
    "    Proof.from_smt2(%s, %s, %s, %s, %s, %s, %s, %s, %s, \
     r\"\"\"\n%s\"\"\"),\n"
    p.kernel p.array p.indices p.globals p.task1 p.task2 p.variables p.logic
    p.is_bv p.smt

let render (filename : string) (output : Analysis.t list) : unit =
  Out_channel.with_open_text filename (fun oc ->
      output_string oc (header Z3.Version.to_string);
      output
      |> List.iter (fun (analysis : Analysis.t) ->
             let kernel_name = analysis.kernel.name in
             analysis.report
             |> List.filter_map (to_pyz3_proof kernel_name)
             |> List.iter (serialize oc));
      output_string oc footer)
