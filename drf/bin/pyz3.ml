def _z3_version(v: str) -> tuple:
    return tuple(int(p) for p in v.split(".")[:2] if p.isdigit())


if _z3_version(z3.get_version_string()) != _z3_version(FAIAL_Z3_VERSION):
    warnings.warn(
        f"these proofs were generated with z3 {FAIAL_Z3_VERSION}, but z3 "
        f"{z3.get_version_string()} is installed; SMT-LIB is usually "
        f"compatible across z3 releases, but if a proof fails to parse or "
        f"behaves oddly, install a matching z3-solver.",
        stacklevel=2,
    )


@dataclass
class Task:
    """One conflicting thread: its local variable values (threadIdx.{x,y,z}
    and loop counters), the access mode ('ro' read / 'rw' write), and the
    source location of the racing access."""

    locals: dict
    mode: str
    location: dict


@dataclass
class Proof:
    """A racy proof obligation from faial-drf, ready to explore in z3.

    `solver.check()` returns sat and reproduces the counterexample faial
    found. `array` and `indices` are the array and the subscript where the
    two threads collide. `globals` is the shared parameter/geometry
    assignment it chose; `task1` and `task2` are the two colliding threads
    (each a Task with `locals`, `mode`, and the access `location`).
    `data_approx` / `control_approx` name the over-approximated variables:
    both empty is a precise counterexample (CIDI); a non-empty `data_approx`
    is a data-dependent index that no parameter assumption can discharge.
    `locations` maps a symbol to its source location where faial knows one.
    A thread-local `X` is the solver constant `X$T1` for task1 and `X$T2` for
    task2; globals keep their plain name, and sym()/var() translate between
    the dict keys and the solver symbols. Add candidate assumptions and
    re-check; push()/pop() keep the base query intact:

        p = proofs[0]
        p.solver.check()                       # sat
        p.globals                              # {'nb1': 0, ...}
        p.task1.locals, p.task1.mode           # {'threadIdx.x': 32, ...}, 'rw'
        i1, i2 = z3.Int("threadIdx.x$T1"), z3.Int("threadIdx.x$T2")
        p.solver.push(); p.solver.add(i1 == i2)
        p.solver.check()                       # sat / unsat under the assumption
        p.solver.pop()

    An unsat means the assumption removes this counterexample: a lead, not a
    DRF proof (one proof, no reachability or vacuity gate). Confirm a
    promising assumption with `faial-drf --assume "..."`.
    """

    kernel: str
    array: str
    indices: list
    globals: dict
    task1: Task
    task2: Task
    data_approx: list
    control_approx: list
    locations: dict
    solver: z3.Solver

    @classmethod
    def from_smt2(
        cls,
        kernel: str,
        array: str,
        indices: list,
        globals: dict,
        task1: Task,
        task2: Task,
        data_approx: list,
        control_approx: list,
        locations: dict,
        smt2: str,
    ) -> "Proof":
        solver = z3.Solver()
        solver.add(z3.parse_smt2_string(smt2))
        return cls(
            kernel, array, indices, globals, task1, task2,
            data_approx, control_approx, locations, solver,
        )

    def sym(self, name: str, task: int | None = None) -> str:
        """z3 symbol name for a high-level variable: the plain name for a
        global, or `name$T1` / `name$T2` for a task1 / task2 local."""
        return name if task is None else f"{name}$T{task}"

    def var(self, symbol: str) -> tuple[int | None, str] | None:
        """Inverse of sym: (task, name) for a solver symbol, task being 1, 2,
        or None (a global); None for faial's internal $-prefixed symbols.
        Cross-reference a model with: `p.var(d.name())` for `d` in model."""
        for t in (1, 2):
            suffix = f"$T{t}"
            if symbol.endswith(suffix):
                return t, symbol[: -len(suffix)]
        return None if symbol.startswith("$") else (None, symbol)


